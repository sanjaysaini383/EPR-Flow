import "server-only";
import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import { formatCell, type ReportDocument, type ReportSection } from "@/lib/domain/reports/types";

// A4 landscape, in points.
const PAGE = { width: 841.89, height: 595.28 };
const MARGIN = 36;
const CONTENT_WIDTH = PAGE.width - MARGIN * 2;
const FOOTER_Y = 22;

const INK = rgb(0.1, 0.12, 0.11);
const MUTED = rgb(0.4, 0.42, 0.41);
const BRAND = rgb(0.08, 0.5, 0.24);
const HEADER_BG = rgb(0.91, 0.95, 0.92);
const ZEBRA = rgb(0.97, 0.98, 0.97);
const RULE = rgb(0.8, 0.82, 0.81);

const SIZE = { title: 18, subtitle: 10, section: 11.5, body: 8, small: 7 };
const CELL_PAD = 3;
const NUMERIC_PAD_RIGHT = 9; // gap between a right-aligned number and the next column's text

/**
 * Renders a report as a PDF using the standard Helvetica fonts. Those fonts only
 * cover WinAnsi characters, so text is normalised first (₹ → "Rs.", unknown → "?").
 */
export async function renderPdf(doc: ReportDocument): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  pdf.setTitle(`${doc.title} — ${doc.organizationName}`);
  pdf.setAuthor("EPRFlow");
  pdf.setCreator("EPRFlow");
  pdf.setCreationDate(doc.generatedAt);
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const italic = await pdf.embedFont(StandardFonts.HelveticaOblique);

  const safe = makeSanitizer(regular);
  let page: PDFPage = pdf.addPage([PAGE.width, PAGE.height]);
  let y = PAGE.height - MARGIN;

  const newPage = () => {
    page = pdf.addPage([PAGE.width, PAGE.height]);
    y = PAGE.height - MARGIN;
  };
  const ensure = (height: number) => {
    if (y - height < MARGIN + FOOTER_Y) newPage();
  };
  const text = (value: string, x: number, size: number, font: PDFFont, color = INK) => {
    page.drawText(safe(value), { x, y, size, font, color });
  };

  // Title block
  page.drawRectangle({ x: MARGIN, y: y - 4, width: 4, height: 34, color: BRAND });
  y -= 14;
  text(doc.title, MARGIN + 12, SIZE.title, bold);
  y -= 16;
  text(`${doc.organizationName}  ·  ${doc.subtitle}`, MARGIN + 12, SIZE.subtitle, regular, MUTED);
  y -= 24;

  for (const section of doc.sections) {
    ensure(110); // keep a heading together with its table header and first rows
    text(section.title, MARGIN, SIZE.section, bold, BRAND);
    y -= 6;
    if (section.note) {
      for (const line of wrap(safe(section.note), italic, SIZE.small, CONTENT_WIDTH)) {
        y -= 9;
        text(line, MARGIN, SIZE.small, italic, MUTED);
      }
    }
    y -= 6;
    if (section.layout === "fields") drawFields(section);
    else drawTable(section);
    y -= 16;
  }

  if (doc.disclaimer) {
    const lines = wrap(safe(doc.disclaimer), italic, SIZE.small, CONTENT_WIDTH);
    ensure(lines.length * 9 + 8);
    for (const line of lines) {
      y -= 9;
      text(line, MARGIN, SIZE.small, italic, MUTED);
    }
  }

  // Footer on every page
  const pages = pdf.getPages();
  const stamp = new Intl.DateTimeFormat("en-IN", { dateStyle: "medium", timeStyle: "short", timeZone: "Asia/Kolkata" }).format(doc.generatedAt);
  pages.forEach((p, i) => {
    p.drawText(safe(`Generated by EPRFlow on ${stamp} IST`), { x: MARGIN, y: FOOTER_Y, size: SIZE.small, font: regular, color: MUTED });
    const label = `Page ${i + 1} of ${pages.length}`;
    p.drawText(label, { x: PAGE.width - MARGIN - regular.widthOfTextAtSize(label, SIZE.small), y: FOOTER_Y, size: SIZE.small, font: regular, color: MUTED });
  });

  return pdf.save();

  function drawFields(section: ReportSection) {
    const labelWidth = 190;
    for (const row of section.rows) {
      const lines = wrap(safe(formatCell(row.value, "text", "Rs.")), regular, SIZE.body + 1, CONTENT_WIDTH - labelWidth);
      const height = lines.length * 11 + 4;
      ensure(height);
      y -= 11;
      text(formatCell(row.field, "text"), MARGIN, SIZE.body + 1, bold, MUTED);
      lines.forEach((line, i) => {
        page.drawText(line, { x: MARGIN + labelWidth, y: y - i * 11, size: SIZE.body + 1, font: regular, color: INK });
      });
      y -= (lines.length - 1) * 11 + 4;
      page.drawLine({ start: { x: MARGIN, y: y }, end: { x: MARGIN + CONTENT_WIDTH, y }, thickness: 0.4, color: RULE });
    }
  }

  function drawTable(section: ReportSection) {
    const weights = section.columns.map((c) => c.width ?? (c.kind === "text" ? 18 : 13));
    const total = weights.reduce((a, b) => a + b, 0);
    const widths = weights.map((w) => (w / total) * CONTENT_WIDTH);
    const xs = widths.map((_, i) => MARGIN + widths.slice(0, i).reduce((a, b) => a + b, 0));
    const numeric = section.columns.map((c) => c.kind !== "text");
    const lineHeight = SIZE.body + 2.5;

    const cellLines = (values: string[], font: PDFFont) =>
      values.map((v, i) => wrap(safe(v), font, SIZE.body, widths[i] - CELL_PAD - (numeric[i] ? NUMERIC_PAD_RIGHT : CELL_PAD)));

    const drawRow = (lines: string[][], font: PDFFont, fill?: ReturnType<typeof rgb>) => {
      const height = Math.max(1, ...lines.map((l) => l.length)) * lineHeight + CELL_PAD * 2;
      if (fill) page.drawRectangle({ x: MARGIN, y: y - height, width: CONTENT_WIDTH, height, color: fill });
      lines.forEach((cell, i) => {
        cell.forEach((line, j) => {
          const w = font.widthOfTextAtSize(line, SIZE.body);
          const x = numeric[i] ? xs[i] + widths[i] - NUMERIC_PAD_RIGHT - w : xs[i] + CELL_PAD;
          page.drawText(line, { x, y: y - CELL_PAD - SIZE.body - j * lineHeight + 1, size: SIZE.body, font, color: INK });
        });
      });
      y -= height;
    };

    const headerLines = cellLines(section.columns.map((c) => c.label), bold);
    const headerHeight = Math.max(...headerLines.map((l) => l.length)) * lineHeight + CELL_PAD * 2;
    const drawHeader = () => drawRow(headerLines, bold, HEADER_BG);

    ensure(headerHeight + lineHeight * 2);
    drawHeader();
    if (section.rows.length === 0) {
      y -= 12;
      text("No records.", MARGIN + CELL_PAD, SIZE.body, italic, MUTED);
      y -= 4;
      return;
    }
    section.rows.forEach((row, index) => {
      const lines = cellLines(section.columns.map((c) => formatCell(row[c.key], c.kind, "Rs.")), regular);
      const height = Math.max(...lines.map((l) => l.length)) * lineHeight + CELL_PAD * 2;
      if (y - height < MARGIN + FOOTER_Y) {
        newPage();
        drawHeader();
      }
      drawRow(lines, regular, index % 2 === 1 ? ZEBRA : undefined);
    });
    if (section.totals) {
      const totals = section.totals;
      const lines = cellLines(section.columns.map((c) => (totals[c.key] === undefined ? "" : formatCell(totals[c.key], c.kind, "Rs."))), bold);
      ensure(lineHeight + CELL_PAD * 2);
      page.drawLine({ start: { x: MARGIN, y }, end: { x: MARGIN + CONTENT_WIDTH, y }, thickness: 0.8, color: INK });
      drawRow(lines, bold);
    }
  }
}

const REPLACEMENTS: Record<string, string> = { "₹": "Rs.", " ": " ", " ": " ", " ": " ", "≥": ">=", "≤": "<=", "→": "->" };

/** Maps text onto characters the standard font can encode. */
function makeSanitizer(font: PDFFont) {
  const ok = new Map<string, boolean>();
  return (value: string) =>
    Array.from(value.replace(/[\r\n\t]+/g, " "))
      .map((ch) => {
        if (REPLACEMENTS[ch] !== undefined) return REPLACEMENTS[ch];
        if (!ok.has(ch)) {
          try {
            font.encodeText(ch);
            ok.set(ch, true);
          } catch {
            ok.set(ch, false);
          }
        }
        return ok.get(ch) ? ch : "?";
      })
      .join("");
}

/** Greedy word wrap; words longer than the width are split. */
function wrap(value: string, font: PDFFont, size: number, width: number): string[] {
  if (!value) return [""];
  const lines: string[] = [];
  let line = "";
  for (const word of value.split(" ")) {
    const candidate = line ? `${line} ${word}` : word;
    if (font.widthOfTextAtSize(candidate, size) <= width) {
      line = candidate;
      continue;
    }
    if (line) lines.push(line);
    line = word;
    while (font.widthOfTextAtSize(line, size) > width && line.length > 1) {
      let cut = line.length - 1;
      while (cut > 1 && font.widthOfTextAtSize(line.slice(0, cut), size) > width) cut--;
      lines.push(line.slice(0, cut));
      line = line.slice(cut);
    }
  }
  if (line) lines.push(line);
  return lines;
}
